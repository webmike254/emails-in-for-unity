// tools/embed-templates.mjs
// Regenerates api/_lib/templates-data.mjs from the root *.html template files.
// The serverless bundler includes JS modules but not arbitrary runtime file
// reads, so the four templates are embedded as strings to guarantee they are
// part of every Lambda deployment.
//
// Run this whenever you edit a template HTML file:
//   node tools/embed-templates.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const OUT = join(ROOT, 'api/_lib/templates-data.mjs');

const FILES = {
  hr: 'congrats-from-hr.html',
  hiring: 'congrats-from-hiring.html',
  director: 'congrats-from-director.html',
  generic: 'congratulation-email.html',
  custom: 'custom-email.html'
};

function toTemplateLiteral(content) {
  return content
    .replace(/\\/g, '\\\\')
    .replace(/`/g, '\\`')
    .replace(/\$\{/g, '\\${');
}

const blocks = [];
for (const [id, file] of Object.entries(FILES)) {
  const content = readFileSync(join(ROOT, file), 'utf-8');
  blocks.push(`export const TEMPLATE_${id.toUpperCase()} = \`${toTemplateLiteral(content)}\`;`);
  console.log(`  embedded ${file} (${content.length} chars) -> ${id}`);
}

const output = `// AUTO-GENERATED by tools/embed-templates.mjs — do not edit by hand.
// Contains the four email templates so they ship inside every serverless
// function bundle. Rerun:  node tools/embed-templates.mjs
\n${blocks.join('\n\n')}\n`;

writeFileSync(OUT, output, 'utf-8');
console.log(`\nWrote ${OUT}`);